"""
Construct the frozen adaptation subset, the SFT dataset, and the DPO
preference pairs — see PLAN.md §4.2.

Run once, at the start of the study, after the pre-registration is committed
and BEFORE any training. All sampling is seeded from configs/seeds.yaml.

Outputs (all cached to disk):
  data/adaptation_ids.json     — frozen list of 4,000 MedMCQA IDs
  data/sft_dataset.jsonl       — {prompt, response, id} per line
  data/dpo_pairs.jsonl         — {prompt, chosen, rejected, id} per line
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import yaml


ADAPTATION_SIZE = 4_000


def load_seeds(seeds_path: Path) -> dict:
    with seeds_path.open() as f:
        return yaml.safe_load(f)


def freeze_adaptation_ids(
    medmcqa_train_ids: list[str],
    out_path: Path,
    seed: int,
    size: int = ADAPTATION_SIZE,
) -> list[str]:
    """
    Sample `size` MedMCQA training-set IDs using the pre-registered seed and
    write them to disk as a JSON array. If the file already exists, it is
    NOT overwritten — this file is the frozen sample and must be immutable
    once committed.
    """
    if out_path.exists():
        with out_path.open() as f:
            existing = json.load(f)
        if len(existing) != size:
            raise RuntimeError(
                f"{out_path} exists with {len(existing)} IDs but expected {size}. "
                "Refusing to overwrite a locked pre-registration artifact."
            )
        return existing
    rng = random.Random(seed)
    sampled = rng.sample(medmcqa_train_ids, size)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        json.dump(sampled, f, indent=2)
    return sampled


def build_sft_dataset(
    medmcqa_train_by_id: dict,
    adaptation_ids: list[str],
    out_path: Path,
    instruction: str,
) -> None:
    """
    Write SFT (instruction, response) pairs.

    Assumes each MedMCQA record has: `question`, `opa`, `opb`, `opc`, `opd`,
    `cop` (0-indexed correct option), `exp` (ground-truth explanation).
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        for qid in adaptation_ids:
            r = medmcqa_train_by_id[qid]
            prompt = (
                f"{instruction}\n\n"
                f"Question: {r['question']}\n"
                f"A) {r['opa']}\nB) {r['opb']}\nC) {r['opc']}\nD) {r['opd']}"
            )
            letter = "ABCD"[r["cop"]]
            explanation = r.get("exp") or "(no explanation provided)"
            response = f"{letter}) {explanation}"
            f.write(json.dumps({
                "id": qid, "prompt": prompt, "response": response,
            }) + "\n")


def build_dpo_pairs(
    medmcqa_train_by_id: dict,
    adaptation_ids: list[str],
    out_path: Path,
    instruction: str,
    base_model_generate_fn,  # callable(prompt: str, seed: int) -> str
    seed: int,
) -> None:
    """
    Construct DPO preference pairs per PLAN.md §4.2.

    Chosen  = ground-truth explanation (identical to SFT target).
    Rejected =
      - the base model's own generation, IF it produced the wrong letter, ELSE
      - a distractor generated by conditioning the base model on a wrong-answer
        letter and asking for a justification.

    `base_model_generate_fn` is injected so this function is testable and so
    the Colab notebook can wire up the actual model. It must be deterministic
    given the same (prompt, seed) input.
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        for i, qid in enumerate(adaptation_ids):
            r = medmcqa_train_by_id[qid]
            correct_letter = "ABCD"[r["cop"]]
            explanation = r.get("exp") or "(no explanation provided)"
            prompt = (
                f"{instruction}\n\n"
                f"Question: {r['question']}\n"
                f"A) {r['opa']}\nB) {r['opb']}\nC) {r['opc']}\nD) {r['opd']}"
            )
            chosen = f"{correct_letter}) {explanation}"

            # Try base-model generation first
            gen = base_model_generate_fn(prompt, seed=seed + i)
            gen_letter = _extract_letter(gen)

            if gen_letter is not None and gen_letter != correct_letter:
                rejected = gen
            else:
                # Fall back to distractor generation conditioned on wrong letter
                distractors = [l for l in "ABCD" if l != correct_letter]
                wrong_letter = distractors[i % len(distractors)]
                distractor_prompt = (
                    f"{prompt}\n\n"
                    f"Explain why the answer is {wrong_letter}."
                )
                rejected = base_model_generate_fn(
                    distractor_prompt, seed=seed + i + 1_000_000
                )
                # Prepend the wrong letter so the shape matches `chosen`
                if not rejected.strip().startswith(wrong_letter):
                    rejected = f"{wrong_letter}) {rejected.strip()}"

            f.write(json.dumps({
                "id": qid,
                "prompt": prompt,
                "chosen": chosen,
                "rejected": rejected,
            }) + "\n")


def _extract_letter(text: str) -> str | None:
    """Return the first A/B/C/D letter found at the start of `text` (loosely)."""
    text = text.lstrip()
    if not text:
        return None
    first = text[0].upper()
    if first in "ABCD":
        return first
    return None


def _cli() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--stage", choices=["freeze_ids", "sft", "dpo"], required=True)
    ap.add_argument("--seeds-config", type=Path, default=Path("configs/seeds.yaml"))
    ap.add_argument("--sft-config", type=Path, default=Path("configs/sft.yaml"))
    ap.add_argument("--dpo-config", type=Path, default=Path("configs/dpo.yaml"))
    ap.add_argument("--out-dir", type=Path, default=Path("data"))
    args = ap.parse_args()

    seeds = load_seeds(args.seeds_config)
    raise NotImplementedError(
        "This CLI is a stub for local testing. The full pipeline runs from "
        "notebooks/run_all_colab.ipynb, which wires up the HuggingFace dataset "
        "load, the base-model generation function, and calls the routines in "
        "this module directly. Kept as CLI for future local reproduction."
    )


if __name__ == "__main__":
    _cli()
